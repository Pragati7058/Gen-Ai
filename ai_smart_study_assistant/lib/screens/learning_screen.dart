import '../core/responsive_utils.dart';
import 'package:flutter/material.dart';

import '../core/theme/app_theme.dart';
import '../models/learning_content.dart';
import '../widgets/gradient_background.dart';
import '../widgets/gradient_button.dart';
import '../widgets/section_title.dart';
import 'quiz_generator_screen.dart';

/// Displays a structured, AI-generated learning experience.
class LearningScreen extends StatelessWidget {
  final LearningContent content;

  const LearningScreen({super.key, required this.content});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: GradientBackground(
        child: SafeArea(
          child: Column(
            children: [
              _header(context),
              Expanded(
                child: ListView(
                  padding: AppResponsive.contentPadding(context, bottom: 120),
                  children: [
                    _topicHero(context),
                    const SizedBox(height: 20),
                    _overviewCard(context),
                    const SizedBox(height: 16),
                    _flowSection(context),
                    const SizedBox(height: 16),
                    _examplesSection(context),
                    const SizedBox(height: 8),
                    ..._sections(context),
                    const SizedBox(height: 24),
                    _tryItOut(context),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
      floatingActionButton: FloatingActionButton.extended(
        onPressed: () => Navigator.of(context).pop(),
        icon: const Icon(Icons.arrow_back),
        label: const Text('Home'),
      ),
    );
  }

  Widget _header(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    return Padding(
      padding: AppResponsive.headerPadding(context),
      child: Row(
        children: [
          IconButton(
            onPressed: () => Navigator.of(context).maybePop(),
            icon: const Icon(Icons.arrow_back_ios_new_rounded),
            color: scheme.onSurface,
          ),
          const Text('🪄'),
          const SizedBox(width: 8),
          Expanded(
            child: Text(
              'AI Learning Experience',
              style: Theme.of(context)
                  .textTheme
                  .titleLarge
                  ?.copyWith(color: scheme.onSurface),
            ),
          ),
        ],
      ),
    );
  }

  Widget _topicHero(BuildContext context) {
    final radius = AppResponsive.responsiveRadius(context);
    return Container(
      padding: AppResponsive.containerPadding(context),
      decoration: BoxDecoration(
        gradient: AppColors.brandGradient,
        borderRadius: BorderRadius.circular(radius),
        boxShadow: [
          BoxShadow(
            color: AppColors.primary.withValues(alpha:0.35),
            blurRadius: 22,
            offset: const Offset(0, 10),
          ),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const Text(
            '✨ Learning Guide',
            style: TextStyle(color: Colors.white70, fontWeight: FontWeight.w600),
          ),
          const SizedBox(height: 6),
          Text(
            content.topic,
            style: Theme.of(context).textTheme.headlineMedium?.copyWith(
                  color: Colors.white,
                  fontWeight: FontWeight.w800,
                ),
          ),
          const SizedBox(height: 10),
          const Text(
            'Generated by Generative AI, personalized for you.',
            style: TextStyle(color: Colors.white70),
          ),
        ],
      ),
    );
  }

  Widget _overviewCard(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final radius = AppResponsive.responsiveRadius(context);
    return Container(
      padding: AppResponsive.containerPadding(context),
      decoration: BoxDecoration(
        gradient: LinearGradient(
          colors: isDark 
              ? [scheme.surfaceContainerHighest, scheme.surfaceContainerHigh]
              : [scheme.surfaceContainerHighest, scheme.surface],
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
        ),
        borderRadius: BorderRadius.circular(radius),
        border: Border.all(color: AppColors.primary.withValues(alpha: 0.1)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SectionTitle(title: 'Overview', icon: '📌'),
          Text(
            content.overview,
            style: TextStyle(color: scheme.onSurfaceVariant, fontSize: 15, height: 1.5),
          ),
        ],
      ),
    );
  }
Widget _flowSection(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final radius = AppResponsive.responsiveRadius(context);
    return Container(
      padding: AppResponsive.containerPadding(context),
      decoration: BoxDecoration(
        gradient: LinearGradient(
          colors: isDark 
              ? [scheme.surfaceContainerHighest, scheme.surfaceContainerHigh]
              : [scheme.surfaceContainerHighest, scheme.surface],
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
        ),
        borderRadius: BorderRadius.circular(radius),
        border: Border.all(color: AppColors.primary.withValues(alpha: 0.1)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SectionTitle(title: 'How It Works', icon: '⚙️'),
          ...List.generate(content.flow.length, (i) {
            final step = content.flow[i];
            return Column(
              children: [
                Row(
                  children: [
                    Container(
                      width: 46,
                      height: 46,
                      decoration: BoxDecoration(
                        gradient: AppColors.subtleGradient,
                        shape: BoxShape.circle,
                        border: Border.all(color: AppColors.primary.withValues(alpha: 0.3)),
                      ),
                      child: Center(
                        child: Text(
                          step.icon,
                          style: const TextStyle(fontSize: 22),
                        ),
                      ),
                    ),
                    const SizedBox(width: 14),
                    Expanded(
                      child: Text(
                        step.label,
                        style: Theme.of(context)
                            .textTheme
                            .titleMedium
                            ?.copyWith(color: scheme.onSurface),
                      ),
                    ),
                  ],
                ),
                if (i < content.flow.length - 1)
                  Padding(
                    padding:
                        const EdgeInsets.only(left: 22, top: 4, bottom: 4),
                    child: Icon(
                      Icons.arrow_downward_rounded,
                      color: AppColors.primary.withValues(alpha:0.5),
                      size: 20,
                    ),
                  ),
              ],
            );
          }),
        ],
      ),
    );
  }

  Widget _examplesSection(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final radius = AppResponsive.responsiveRadius(context);
    return Container(
      padding: AppResponsive.containerPadding(context),
      decoration: BoxDecoration(
        gradient: LinearGradient(
          colors: isDark 
              ? [scheme.surfaceContainerHighest, scheme.surfaceContainerHigh]
              : [scheme.surfaceContainerHighest, scheme.surface],
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
        ),
        borderRadius: BorderRadius.circular(radius),
        border: Border.all(color: AppColors.primary.withValues(alpha: 0.1)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SectionTitle(title: 'Real World Examples', icon: '🌍'),
          GridView.count(
            crossAxisCount: AppResponsive.gridCrossAxisCount(context, minWidthPerTile: 150, minCount: 2, maxCount: 3),
            shrinkWrap: true,
            physics: const NeverScrollableScrollPhysics(),
            mainAxisSpacing: 12,
            crossAxisSpacing: 12,
            childAspectRatio: 1.5,
            children:
                content.examples.map((e) => _exampleCard(context, e)).toList(),
          ),
        ],
      ),
    );
  }
Widget _exampleCard(BuildContext context, RealWorldExample example) {
    final scheme = Theme.of(context).colorScheme;
    final radius = AppResponsive.responsiveRadius(context, min: 14, max: 20);
    final iconSize = AppResponsive.iconSize(context, base: 24);
    final fontSize = AppResponsive.responsiveFontSize(context, min: 10, max: 12);
    return Container(
      padding: AppResponsive.innerPadding(context),
      decoration: BoxDecoration(
        color: example.color.withValues(alpha:0.10),
        borderRadius: BorderRadius.circular(radius),
        border: Border.all(color: example.color.withValues(alpha:0.25)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(example.icon, style: TextStyle(fontSize: iconSize)),
          const Spacer(),
          Text(
            example.title,
            maxLines: 1,
            overflow: TextOverflow.ellipsis,
            style: Theme.of(context)
                .textTheme
                .titleSmall
                ?.copyWith(color: scheme.onSurface, fontWeight: FontWeight.w700),
          ),
          SizedBox(height: AppResponsive.gapWidth(context, base: 2)),
          Text(
            example.subtitle,
            maxLines: 2,
            overflow: TextOverflow.ellipsis,
            style: TextStyle(color: scheme.onSurfaceVariant, fontSize: fontSize),
          ),
        ],
      ),
    );
  }

  List<Widget> _sections(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final isDark = Theme.of(context).brightness == Brightness.dark;
    return content.sections.map((section) {
      final radius = AppResponsive.responsiveRadius(context);
      return Container(
        margin: EdgeInsets.only(top: AppResponsive.gapWidth(context, base: 12)),
        padding: AppResponsive.containerPadding(context),
        decoration: BoxDecoration(
          gradient: LinearGradient(
            colors: isDark 
                ? [scheme.surfaceContainerHighest, scheme.surfaceContainerHigh]
                : [scheme.surfaceContainerHighest, scheme.surface],
            begin: Alignment.topLeft,
            end: Alignment.bottomRight,
          ),
          borderRadius: BorderRadius.circular(radius),
          border: Border.all(color: AppColors.primary.withValues(alpha: 0.1)),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            SectionTitle(title: section.title, icon: section.icon),
            Text(
              section.content,
              style: TextStyle(
                color: scheme.onSurfaceVariant,
                fontSize: 15,
                height: 1.5,
              ),
            ),
          ],
        ),
      );
    }).toList();
  }

  Widget _tryItOut(BuildContext context) {
    final radius = AppResponsive.responsiveRadius(context);
    return Container(
      padding: AppResponsive.containerPadding(context),
      decoration: BoxDecoration(
        gradient: AppColors.subtleGradient,
        borderRadius: BorderRadius.circular(radius),
        border: Border.all(color: AppColors.primary.withValues(alpha:0.2)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SectionTitle(title: 'Try It Yourself', icon: '🧪'),
          const SizedBox(height: 6),
          GradientButton(
            label: 'Generate Quiz',
            icon: Icons.quiz_rounded,
            onPressed: () {
              Navigator.of(context).push(
                MaterialPageRoute(
                  builder: (_) =>
                      QuizGeneratorScreen(defaultTopic: content.topic),
                ),
              );
            },
          ),
        ],
      ),
    );
  }
}
